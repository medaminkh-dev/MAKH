# MAKH UFUZZ U5.1 — emit the documented-errno table as a C header.
#
# The ABI inventory (makh_syscalls.json) lists, per syscall, the errnos it may
# return. The guest executor (/bin/ufuzz) fails any call returning a negative
# errno outside that set. Fails closed on unknown names / oversize lists.
#
#   python3 fuzz/abi/emit_errno.py            # regenerate the header
#   python3 fuzz/abi/emit_errno.py --check    # fail if the committed header is stale

import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
JSON = os.path.join(ROOT, "fuzz", "abi", "makh_syscalls.json")
ERRNO_H = os.path.join(ROOT, "kernel", "include", "errno.h")
HDR = os.path.join(ROOT, "user", "ufuzz_abi_errno.h")
MAXE = 12


def render():
    abi = json.load(open(JSON))
    nums = {m.group(1): int(m.group(2)) for m in
            re.finditer(r"^#define\s+(E[A-Z0-9]+)\s+(\d+)", open(ERRNO_H).read(), re.M)}
    rows, bad = {}, []
    for s in abi["syscalls"]:
        names = s.get("errno", [])
        if len(names) > MAXE:
            bad.append("%s: %d errnos (max %d)" % (s.get("impl", s["nr"]), len(names), MAXE))
        vals = []
        for n in names:
            if n not in nums:
                bad.append("%s: undefined errno %s" % (s.get("impl", s["nr"]), n))
            else:
                vals.append(nums[n])
        rows[s["nr"]] = (names, sorted(set(vals)))
    if bad:
        print("EMIT ERRNO: FAIL —\n  " + "\n  ".join(bad), file=sys.stderr)
        sys.exit(1)
    L = ["/* SPDX-License-Identifier: AGPL-3.0-only */",
         "/* Copyright (C) 2026 Amine Khemissi */",
         "/* GENERATED by fuzz/abi/emit_errno.py — do not edit. Regenerate:",
         " *   python3 fuzz/abi/emit_errno.py   (and `make abi-check` / CI verifies freshness) */",
         "#ifndef MAKHOS_UFUZZ_ABI_ERRNO_H",
         "#define MAKHOS_UFUZZ_ABI_ERRNO_H", "",
         "typedef struct { short nr; unsigned char n; unsigned char e[%d]; } u3_abi_errno_row;" % MAXE, "",
         "static const u3_abi_errno_row U3_ABI_ERRNO[] = {"]
    for nr in sorted(rows):
        names, vals = rows[nr]
        e = ", ".join(str(v) for v in vals) if vals else "0"
        L.append("    { %d, %d, { %s } },   /* %s */" % (nr, len(vals), e, " ".join(names) or "-"))
    L += ["};", "",
          "/* 1 if -err is documented for syscall nr, or nr is not in the table (not our",
          " * contract); 0 if a documented syscall returned an undocumented errno. */",
          "static int u3_abi_errno_ok(long nr, long err) {",
          "    for (unsigned i = 0; i < sizeof(U3_ABI_ERRNO) / sizeof(U3_ABI_ERRNO[0]); i++) {",
          "        if (U3_ABI_ERRNO[i].nr != nr) continue;",
          "        for (unsigned j = 0; j < U3_ABI_ERRNO[i].n; j++)",
          "            if (U3_ABI_ERRNO[i].e[j] == err) return 1;",
          "        return 0;",
          "    }",
          "    return 1;",
          "}", "", "#endif", ""]
    return "\n".join(L)


def main():
    text = render()
    if "--check" in sys.argv[1:]:
        cur = open(HDR).read() if os.path.exists(HDR) else ""
        if cur != text:
            print("EMIT ERRNO: STALE — regenerate with `python3 fuzz/abi/emit_errno.py`", file=sys.stderr)
            sys.exit(1)
        print("EMIT ERRNO: header is up to date")
    else:
        with open(HDR, "w") as f:
            f.write(text)
        print("wrote %s" % os.path.relpath(HDR, ROOT))


main()
